"""Synthetic logs for TESTING the analysis pipeline only.

Every value here is generated by a simple model, not measured. Use it to check
that analyze.py runs and that the figures look right before the real
experiments. Never report these numbers: run analyze.py on your own logs.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np

HEADER = ("ms,label,mark,mode,tilt_deg,ldr_a,ldr_b,imbalance,photo_mv,panel_v,ina_a,acs_a,"
          "current_a,trusted,power_w,soil_naive,soil_light,rule_a,rule_b,soil_valid,"
          "panel_c,air_c,humidity,supply_v,wiper,panel_connected,servo_power,selftest,faults")
L0, I0, R = 1500.0, 0.30, 4.4           # light (mV), clean current (A), load (ohm)
K = I0 / L0


class Log:
    def __init__(self, rng):
        self.rng, self.ms, self.lines = rng, 0, ["# SYNTHETIC TEST DATA - not measured", HEADER]

    def row(self, label, light, factor, *, mark="", mode="auto", wiper=0, connected=1, faults="",
            panel_c=38.0, light_panel=None):
        r = self.rng
        lp = light if light_panel is None else light_panel
        cur = factor * K * lp * (1 + r.normal(0, 0.008)) if connected else 0.0
        ina, acs = cur, cur + r.normal(0, 0.006)
        v = cur * R if connected else 0.0
        photo = light * (1 + r.normal(0, 0.004))
        naive, lightr = cur / I0, cur / (K * photo)
        valid = int(connected and not wiper and photo > 150)
        ra, rb = int(connected and not wiper and naive < 0.8), int(valid and lightr < 0.8)
        self.lines.append(",".join(map(str, [
            self.ms, label, mark, mode, 0, 2400, 2380, 0.004, f"{photo:.0f}", f"{v:.3f}", f"{ina:.4f}",
            f"{acs:.4f}", f"{cur:.4f}", "ina", f"{v * cur:.3f}", f"{naive:.3f}", f"{lightr:.3f}", ra, rb, valid,
            f"{panel_c + r.normal(0, 0.1):.2f}", "29.0", "61", "12.68", wiper, connected, 1, 0, faults])))
        self.ms += 1000

    def save(self, path: Path):
        path.write_text("\n".join(self.lines) + "\n")


def generate(folder: Path, seed: int = 7):
    folder.mkdir(parents=True, exist_ok=True)
    for f in folder.glob("*.csv"):
        f.unlink()
    rng = np.random.default_rng(seed)
    drift = lambda n: L0 * (1 + 0.03 * np.sin(np.linspace(0, 3, n)))  # noqa: E731

    for s in (1, 2):                                       # E1 baseline
        lg = Log(rng)
        for L in drift(600):
            lg.row(f"E1_clean_s{s}", L, 1.0)
        lg.save(folder / f"E1_clean_s{s}.csv")

    levels = {"clean": 1.0, "light": 0.88, "medium": 0.72, "heavy": 0.55}
    for s in (1, 2):                                       # E2 dust levels
        lg = Log(rng)
        for lev, fac in levels.items():
            for L in drift(600):
                lg.row(f"E2_{lev}_s{s}", L, fac * (1 + rng.normal(0, 0.01)))
        lg.save(folder / f"E2_s{s}.csv")

    for s in (1, 2, 3):                                    # E3 shade passes
        lg = Log(rng)
        for i in range(300):
            ph = i % 30
            shade = 0.35 if 10 <= ph < 16 else 1.0
            lead = 0.35 if 9 <= ph < 16 else 1.0          # the card reaches the sensor 1 s early
            lg.row(f"E3_cloud_s{s}", L0 * lead, 1.0, light_panel=L0 * shade, mark="cloud" if ph == 9 else "")
        lg.save(folder / f"E3_cloud_s{s}.csv")

    for lev in ("light", "medium", "heavy"):               # E4 cleaning
        lg = Log(rng)
        for run in range(1, 6):
            fac = levels[lev] * (1 + rng.normal(0, 0.02))
            after = 0.96 + rng.normal(0, 0.015)
            for i in range(60):
                lg.row(f"E4_{lev}_s{run}", L0, fac)
            for i in range(20):
                lg.row(f"E4_{lev}_s{run}", L0, fac, wiper=1, mark="" if i else "")
            for i in range(80):
                lg.row(f"E4_{lev}_s{run}", L0, after)
        lg.save(folder / f"E4_{lev}.csv")

    delays = {"ldr": (5, 1.5), "panel": (3, 0.5), "load": (3, 0.5), "servo": (6, 2), "temp": (45, 15),
              "ina": (3, 0.3), "acs": (3, 0.3)}
    codes = {"ldr": "LDR_MISMATCH", "panel": "PANEL_DISCONNECTED", "load": "NO_CURRENT",
             "servo": "TILT_NO_RESPONSE", "temp": "PANEL_HOT_VS_AIR", "ina": "INA219_MISSING", "acs": "ACS712_FAULT"}
    lg = Log(rng)
    for trial in range(5):                                 # E5 fault injection
        for key, (mu, sd) in delays.items():
            dly = max(1, int(round(rng.normal(mu, sd))))
            if key == "temp" and trial == 4:
                dly = 999                                  # one probe never got hot enough
            for i in range(40):
                lg.row("E5_faults_s1", L0, 1.0)
            for i in range(60):
                lg.row("E5_faults_s1", L0, 1.0, mark=f"inject_{key}" if i == 0 else "",
                       faults=codes[key] if i >= dly else "")
            lg.row("E5_faults_s1", L0, 1.0, mark=f"restore_{key}")
    lg.save(folder / "E5_faults_s1.csv")

    lg = Log(rng)
    for b in range(1, 5):                                  # E6 tracking vs fixed
        base = L0 * (1 + 0.05 * rng.normal())
        for cond, gain in (("fixed", 1.0), ("track", 1.0 + rng.normal(0.18, 0.04))):
            for i in range(1200):
                lg.row(f"E6_{cond}_b{b}", base, gain, mode="auto" if cond == "track" else "fixed")
    lg.save(folder / "E6_s1.csv")
